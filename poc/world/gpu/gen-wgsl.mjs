// The sky (sky.js SKY_GLSL): the air's helpers and the multiple-scattering table's texel, uHaze a private global set by
// each entry. aScatter reads the multiple-scattering table inside its loop, so it is left out: gpu/sky.js marches in TSL
// with these helpers and reads the table itself.
let skyG = SKY_GLSL.replace('uniform float uHaze; // multiplies the Mie density', 'float uHaze = 1.0;').replace('uniform sampler2D uMS; // multiple scattering (Hillaire 2020, section 5.5)', '');
skyG = skyG.replace(/\/\/ in-scattered light along a view ray[\s\S]*?\n}\n(?=\/\/ the sky-view table)/, '');
const msMain = `
vec4 skyMS(vec2 vUv, float haze) {
  uHaze = haze;
  float mus = vUv.x * 2.0 - 1.0, r = A_RG + vUv.y * (A_RT - A_RG) + 1.0;
  vec3 s = vec3(sqrt(max(0.0, 1.0 - mus * mus)), mus, 0.0);
  vec3 L2 = vec3(0.0), fms = vec3(0.0);
  for (int a = 0; a < 8; a++) for (int b = 0; b < 8; b++) {
    float u = (float(a) + 0.5) / 8.0, v = (float(b) + 0.5) / 8.0;
    float cz = 1.0 - 2.0 * v, sz = sqrt(max(0.0, 1.0 - cz * cz)), ph = 6.2831853 * u;
    vec3 w = vec3(sz * cos(ph), cz, sz * sin(ph));
    float tg = aGround(r, w.y), L = tg > 0.0 ? tg : aTop(r, w.y);
    vec3 od = vec3(0.0), Li = vec3(0.0), Fi = vec3(0.0); float dt = L / 20.0;
    for (int i = 0; i < 20; i++) {
      float t = (float(i) + 0.5) * dt; vec3 p = vec3(0.0, r, 0.0) + w * t; float rr = length(p);
      vec3 sR; float sM; vec3 ex = aExt(rr - A_RG, sR, sM); vec3 S = sR + vec3(sM);
      vec3 T = exp(-(od + ex * dt * 0.5));
      Li += T * S * aTransmittance(rr, dot(p / rr, s)) * dt / (4.0 * 3.14159265);
      Fi += T * S * dt;
      od += ex * dt;
    }
    if (tg > 0.0) { vec3 pg = vec3(0.0, r, 0.0) + w * tg; vec3 ng = normalize(pg); Li += exp(-od) * aTransmittance(A_RG + 1.0, dot(ng, s)) * max(dot(ng, s), 0.0) * 0.3 / 3.14159265; }
    L2 += Li / 64.0; fms += Fi / 64.0;
  }
  return vec4(L2 / (1.0 - min(fms, vec3(0.99))), 1.0);
}
// one step's air at altitude h: [0] extinction, [1] Rayleigh scattering, [2].x Mie scattering
mat3 skyAir(float h, float haze) { uHaze = haze; vec3 sR; float sM; vec3 e = aExt(h, sR, sM); return mat3(e, sR, vec3(sM, 0.0, 0.0)); }
vec3 skyTrans(float r, float mu, float haze) { uHaze = haze; return aTransmittance(r, mu); }
`;
const nightG = NIGHT_GLSL.replace('uniform vec3 uMoonDir, uMoonColor;', 'vec3 uMoonDir = vec3(0.0, 1.0, 0.0); vec3 uMoonColor = vec3(0.0); vec3 uSun = vec3(0.0, 1.0, 0.0);')
  + '\nvec3 nightAt(vec3 v, float blur, vec3 sun, vec3 moonDir, vec3 moonColor) { uSun = sun; uMoonDir = moonDir; uMoonColor = moonColor; return nightSky(v, blur); }\n';
const sky = convertPlain(skyG + msMain + nightG, 'outv[i] = skyMS(p, 1.0) + vec4(skyAir(p.x, 1.0)[0], 0.0) + vec4(skyTrans(6360001.0, p.x, 1.0), 0.0) + vec4(aPhaseR(p.x) + aPhaseM(p.x)) + vec4(skyUV(vec3(p, 1.0), vec3(1.0)), skyDir(p, vec3(1.0)).xy) + vec4(nightAt(vec3(p, 1.0), 0.0, vec3(1.0), vec3(1.0), vec3(1.0)), 0.0);');
fs.writeFileSync(path.join(here, 'sky.wgsl.js'), `// Generated by gen-wgsl.mjs from sky.js SKY_GLSL (naga): do not edit; change the GLSL and run it again.\nexport const SKY_WGSL = /* wgsl */ \`\n${sky}\`;\n`);
console.log('sky.wgsl.js', sky.length, 'chars');

// The clouds (clouds.js CLOUD_GLSL): the slab's density, its march and the shadow over a point, the weather's uniforms
// private, set by each entry
const cloudG = NOISE_GLSL + CLOUD_GLSL.replace('uniform float uCover, uCloudDens, uCloudT; uniform vec2 uCloudDrift;', 'float uCover = 0.0; float uCloudDens = 1.0; float uCloudT = 0.0; vec2 uCloudDrift = vec2(0.0);') + `
vec4 cloudMarch(vec3 ro, vec3 rd, float tmax, float jit, vec3 sunCol, vec3 sunDir, vec3 amb, float cover, float dens, vec2 drift) { uCover = cover; uCloudDens = dens; uCloudDrift = drift; return marchClouds(ro, rd, tmax, jit, sunCol, sunDir, amb); }
float cloudShade(vec2 xz, vec3 sun, float cover, float dens, vec2 drift) { uCover = cover; uCloudDens = dens; uCloudDrift = drift; return cloudShadowAt(xz, sun); }
`;
const clouds = convertPlain(cloudG, 'outv[i] = cloudMarch(vec3(p, 0.0), vec3(0.0, 1.0, 0.0), 1e9, 0.5, vec3(1.0), vec3(0.0, 1.0, 0.0), vec3(1.0), 0.5, 1.0, p) + vec4(cloudShade(p, vec3(0.0, 1.0, 0.0), 0.5, 1.0, p));');
fs.writeFileSync(path.join(here, 'clouds.wgsl.js'), `// Generated by gen-wgsl.mjs from clouds.js CLOUD_GLSL (naga): do not edit; change the GLSL and run it again.\nexport const CLOUDS_WGSL = /* wgsl */ \`\n${clouds}\`;\n`);
console.log('clouds.wgsl.js', clouds.length, 'chars');
