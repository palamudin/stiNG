// Builds the WGSL twins of World v3's GLSL (run with node; needs naga, the shader converter: cargo install naga-cli).
// The GLSL stays the source: its numbers come from the same constants as the JS twins (wild.js WILD, RIVER_ROCK),
// so it is converted, not retyped. Writes gpu/wild.wgsl.js: WILD_WGSL, the module's functions with the world's
// parameters as private globals set by wildParams(...), for compute kernels and node materials to include.
//   node poc/world/gpu/gen-wgsl.mjs
import { execFileSync } from 'child_process';
import fs from 'fs';
import os from 'os';
import path from 'path';
import { fileURLToPath } from 'url';
import { wildGLSL } from '../sources/wild.js';
import { NOISE_GLSL } from '../noise.js';
import { SWASH_GLSL, SURF_GLSL } from '../water3/swash.js';
import { FOAM } from '../water3/foamtex.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const NAGA = process.env.NAGA || path.join(os.homedir(), '.cargo/bin/naga');
const PARAMS = [['wSeed', 'i32'], ['wSea', 'f32'], ['wRelief', 'f32'], ['wBlocky', 'f32'], ['wRivers', 'f32'], ['wForests', 'f32'], ['wTrails', 'f32']];

function convert(glsl, uses) {
  const g = glsl.replace(/uniform int wSeed;\s*uniform float wSea, wRelief, wBlocky, wRivers, wForests, wTrails;/,
    `layout(set = 0, binding = 0) uniform WP { ${PARAMS.map(([n, t]) => (t === 'i32' ? 'int ' : 'float ') + n + ';').join(' ')} };`);
  // an entry that calls what is wanted, so naga keeps it
  const src = `#version 450\n${g}\nlayout(set = 0, binding = 1) buffer OutB { vec4 outv[]; };\nlayout(local_size_x = 64) in;\nvoid main() { uint i = gl_GlobalInvocationID.x; vec2 p = vec2(float(i), 0.0); ${uses} }\n`;
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'wgsl-')), a = path.join(dir, 'in.comp'), b = path.join(dir, 'out.wgsl');
  fs.writeFileSync(a, src);
  execFileSync(NAGA, ['--input-kind', 'glsl', '--shader-stage', 'compute', a, b]);
  let w = fs.readFileSync(b, 'utf8');
  // drop the entry, the bindings and their structs; the parameters become private globals
  w = w.replace(/struct WP \{[^}]*\}\n\n?/, '').replace(/struct OutB \{[^}]*\}\n\n?/, '');
  w = w.replace(/@group\(0\) @binding\(\d\) \nvar<[^>]*> global(_1)?: \w+;\n/g, '');
  w = w.replace(/var<private> gl_GlobalInvocationID_1: vec3<u32>;\n/, '');
  w = w.replace(/\nfn main_1\(\) \{[\s\S]*$/, '\n');
  w = w.replace(/global\.(w[A-Z]\w*)/g, '$1');
  const decl = PARAMS.map(([n, t]) => `var<private> ${n}: ${t};`).join('\n');
  const set = `fn wildParams(seed: i32, sea: f32, relief: f32, blocky: f32, rivers: f32, forests: f32, trails: f32) -> f32 {\n  wSeed = seed; wSea = sea; wRelief = relief; wBlocky = blocky; wRivers = rivers; wForests = forests; wTrails = trails;\n  return 0.0;\n}\n`;
  return `${decl}\n${w.trim()}\n\n${set}`;
}

const wild = convert(wildGLSL(), 'outv[i] = wildWaterFlow(p, 0.25) + wildSample(p) + vec4(wildWater(p));');
fs.writeFileSync(path.join(here, 'wild.wgsl.js'), `// Generated by gen-wgsl.mjs from sources/wild.js wildGLSL() (naga): do not edit; change the GLSL and run it again.\nexport const WILD_WGSL = /* wgsl */ \`\n${wild}\`;\n`);
console.log('wild.wgsl.js', wild.length, 'chars');

// The coast (water3/swash.js SWASH_GLSL and SURF_GLSL): pure math but for the shore table, so the table's answer at the
// point is handed in (the WebGPU reader is TSL, gpu/shore.js) and shoreAt returns it; the uniforms are private
// globals set by each entry. Entries: coastVert (the trains, their slope and foam, the edge's shift) and coastEdgeY
// (the sheet over the sand), as water3/surface.js's vertex calls them.
function convertPlain(glsl, uses) {
  const src = `#version 450\n${glsl}\nlayout(set = 0, binding = 1) buffer OutB { vec4 outv[]; };\nlayout(local_size_x = 64) in;\nvoid main() { uint i = gl_GlobalInvocationID.x; vec2 p = vec2(float(i), 0.0); ${uses} }\n`;
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'wgsl-')), a = path.join(dir, 'in.comp'), b = path.join(dir, 'out.wgsl');
  fs.writeFileSync(a, src);
  execFileSync(NAGA, ['--input-kind', 'glsl', '--shader-stage', 'compute', a, b]);
  let w = fs.readFileSync(b, 'utf8');
  w = w.replace(/struct OutB \{[^}]*\}\n\n?/, '').replace(/@group\(0\) @binding\(\d\) \nvar<[^>]*> global(_1)?: \w+;\n/g, '');
  w = w.replace(/var<private> gl_GlobalInvocationID_1: vec3<u32>;\n/, '').replace(/\nfn main_1\(\) \{[\s\S]*$/, '\n');
  return w.trim() + '\n';
}
const coastGLSL = `${NOISE_GLSL}
float gShoreKnow = 0.0; vec4 gShoreIn = vec4(1.0e4, 0.0, 0.0, 1.0e4); float gKnowIn = 0.0;
vec4 shoreAt(vec2 p) { gShoreKnow = gKnowIn; return gShoreIn; }
${SWASH_GLSL.replace('uniform vec4 uSurf, uSurfX; uniform float uWTime; uniform vec2 uSwDir;', 'vec4 uSurf = vec4(0.0); vec4 uSurfX = vec4(0.0); float uWTime = 0.0; vec2 uSwDir = vec2(1.0, 0.0);')}
${SURF_GLSL}
void coastSet(vec4 surf, vec4 surfX, float t, vec2 swDir) { uSurf = surf; uSurfX = surfX; uWTime = t; uSwDir = swDir; }
// the trains here: [0] (displacement, gNear), [1] (slope, foam x y), [2] (foam z, the edge's shift, -, -), [3] (on, -, -, -)
mat4 coastVert(vec2 xz, vec4 sh, float know, float depth, float cell, float fl, vec4 surf, vec4 surfX, float t, vec2 swDir) {
  coastSet(surf, surfX, t, swDir); gShoreIn = sh; gKnowIn = know;
  vec4 c0 = vec4(0.0), c1 = vec4(0.0); float fz = 0.0, on = 0.0;
  if (depth > -3.0 && uSurf.x > 0.0 && sw3Ctx(xz)) {
    on = 1.0;
    if (depth > 0.0) { vec3 d = w3Coast(xz, depth, cell) * (1.0 - fl); c0 = vec4(d, gNear); c1 = vec4(gCoastSlope * (1.0 - fl), gCoastFoam.xy * (1.0 - fl)); fz = gCoastFoam.z * (1.0 - fl); }
  }
  return mat4(c0, c1, vec4(fz, sw3EdgeShift(depth), 0.0, 0.0), vec4(on, 0.0, 0.0, 0.0));
}
float coastEdgeY(vec2 xz, float level, float bed, float py, vec2 grad, float fl, vec4 surf, vec4 surfX, float t, vec2 swDir) { coastSet(surf, surfX, t, swDir); return sw3EdgeY(xz, level, bed, py, grad, t, fl); }
// the shoreline's foam at a pixel: (sw3ShoreFoam, the swash's height over the floor th, s), as surface.js's fragment
vec4 coastShoreFoam(vec2 xz, float depth, vec2 grad, float wave, float fl, vec4 surf, vec4 surfX, float t, vec2 swDir) {
  coastSet(surf, surfX, t, swDir); sw3Beach(xz, grad); gExpo *= 1.0 - fl;
  float s; float th = depth + sw3Shore(xz, length(grad), t, s);
  return vec4(sw3ShoreFoam(depth, th, s, wave), th, s, 0.0);
}
// the sand: (darkness, gloss, covered) as terrain.js reads sw3Wet
vec3 coastWet(vec2 xz, float hgt, vec2 grad, vec4 surf, vec4 surfX, float t, vec2 swDir) { coastSet(surf, surfX, t, swDir); sw3Beach(xz, grad); return sw3Wet(xz, hgt, length(grad), t); }
`;
const coast = convertPlain(coastGLSL, 'mat4 m = coastVert(p, vec4(0.0), 1.0, 1.0, 1.0, 0.0, vec4(1.0), vec4(0.0), 0.0, vec2(1.0, 0.0)); outv[i] = m[0] + vec4(coastEdgeY(p, 0.0, -1.0, 0.0, vec2(0.1), 0.0, vec4(1.0), vec4(0.0), 0.0, vec2(1.0, 0.0))) + coastShoreFoam(p, 0.1, vec2(0.1), 0.0, 0.0, vec4(1.0), vec4(0.0), 0.0, vec2(1.0, 0.0)) + vec4(coastWet(p, 0.1, vec2(0.1), vec4(1.0), vec4(0.0), 0.0, vec2(1.0, 0.0)), 0.0);');
fs.writeFileSync(path.join(here, 'coast.wgsl.js'), `// Generated by gen-wgsl.mjs from water3/swash.js SWASH_GLSL + SURF_GLSL (naga): do not edit; change the GLSL and run it again.\nexport const COAST_WGSL = /* wgsl */ \`\n${coast}\`;\n`);
console.log('coast.wgsl.js', coast.length, 'chars');

